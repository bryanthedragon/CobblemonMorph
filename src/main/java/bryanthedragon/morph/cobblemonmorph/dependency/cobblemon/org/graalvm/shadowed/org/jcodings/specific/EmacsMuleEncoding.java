   @Override
   public int codeToMbcLength(int code) {
      if (isAscii(code)) {
         return 1;
      } else if (code > -1) {
         return 0;
      } else if ((code & 0xFF000000) >= Integer.MIN_VALUE) {
         return 4;
      } else if ((code & 0xFF0000) >= 8388608) {
         return 3;
      } else {
         return (code & 0xFF00) >= 32768 ? 2 : -400;
      }
   }

   @Override
   public int codeToMbc(int code, byte[] bytes, int p) {
      int p_ = p;
      if ((code & 0xFF000000) != 0) {
         p_ = p + 1;
         bytes[p] = (byte)(code >>> 24 & 0xFF);
      }

      if ((code & 0xFF0000) != 0) {
         bytes[p_++] = (byte)(code >>> 16 & 0xFF);
      }

      if ((code & 0xFF00) != 0) {
         bytes[p_++] = (byte)(code >>> 8 & 0xFF);
      }

      bytes[p_++] = (byte)(code & 0xFF);
      return this.length(bytes, p, p_) != p_ - p ? -400 : p_ - p;
   }

